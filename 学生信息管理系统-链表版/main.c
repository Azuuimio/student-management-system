// main.c —— 程序入口与控制台编码设置

// 项目头文件
#include "student.h"
#include "ui.h"

// 标准库头文件
#include <stdio.h>

// Windows API 头文件
#include <windows.h>

// 函数：程序入口。
int main() {
    /*
     * 关于中文乱码问题：
     * 本工程的源文件默认以 UTF-8 无 BOM 格式保存。MSVC 在简体中文 Windows 上未指定
     * 源文件编码时，通常按系统代码页（GBK）解码无 BOM 的文件。常用汉字在 UTF-8 中占
     * 3 字节，在 GBK 中占 2 字节；编码不匹配可能导致编译器误读后续的引号或换行符，
     * 从而报告语法错误，例如：
     *     C2001  常量中有换行符
     *     C2143  语法错误：缺少 ";"（在 "..." 的前面）
     *     C2018  未知字符 '0x...'
     * 报错位置往往集中在含中文的行附近，此时应先检查源文件编码。即使编译通过，
     * 执行字符集与控制台代码页不一致也可能导致中文乱码，可按以下步骤检查：
     * 第一步（编译器）：右键项目 → 属性 → C/C++ → 命令行 → 在“附加选项”中输入
     *     /utf-8 → 确定。
     * 第二步（源文件）：确认各 .c/.h 文件以 UTF-8 保存。也可在 VS2022 中打开文件 →
     *     文件 → 高级保存选项 → 选择“Unicode（UTF-8 带签名）- 代码页 65001” → 保存。
     *     此操作需要逐个文件进行；指定 /utf-8 后，无 BOM 的 UTF-8 文件也可正常识别。
     * 第三步（控制台）：调用 SetConsoleOutputCP / SetConsoleCP 设置输出和输入代码页。
     */
    // 设置控制台输入、输出代码页为 UTF-8
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // 启动菜单
    ui_run();

    return 0;
}
